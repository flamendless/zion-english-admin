// Command embed_flags writes internal/nationalities/flags.go from static/flags/*.svg.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	repoRoot, err := findRepoRoot()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	flagsDir := filepath.Join(repoRoot, "static", "flags")
	entries, err := os.ReadDir(flagsDir)
	if err != nil {
		fmt.Fprintln(os.Stderr, "read flags dir:", err)
		os.Exit(1)
	}

	var ids []string
	byID := make(map[string]string)
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".svg") {
			continue
		}
		id := strings.TrimSuffix(e.Name(), ".svg")
		data, err := os.ReadFile(filepath.Join(flagsDir, e.Name()))
		if err != nil {
			fmt.Fprintln(os.Stderr, e.Name(), err)
			os.Exit(1)
		}
		ids = append(ids, id)
		byID[id] = strings.TrimSpace(string(data))
	}
	sort.Strings(ids)

	outPath := filepath.Join(repoRoot, "internal", "nationalities", "flags.go")
	f, err := os.Create(outPath)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer f.Close()

	fmt.Fprintln(f, "// Code generated by tools/embed_flags. DO NOT EDIT.")
	fmt.Fprintln(f, "")
	fmt.Fprintln(f, "package nationalities")
	fmt.Fprintln(f, "")
	fmt.Fprintln(f, `import "strings"`)
	fmt.Fprintln(f, "")
	fmt.Fprintln(f, "// FlagSVG returns inline flag SVG markup for an ISO 3166-1 alpha-2 code.")
	fmt.Fprintln(f, "func FlagSVG(iso string) string {")
	fmt.Fprintln(f, "\tswitch strings.ToLower(strings.TrimSpace(iso)) {")
	for _, id := range ids {
		svg := byID[id]
		svg = strings.ReplaceAll(svg, "`", "` + \"`\" + `")
		fmt.Fprintf(f, "\tcase %q:\n\t\treturn `%s`\n", id, svg)
	}
	fmt.Fprintln(f, "\tdefault:")
	fmt.Fprintln(f, "\t\treturn \"\"")
	fmt.Fprintln(f, "\t}")
	fmt.Fprintln(f, "}")

	fmt.Printf("Wrote %d flags to %s\n", len(ids), outPath)
}

func findRepoRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("go.mod not found")
		}
		dir = parent
	}
}
