package parentpaymentocr

import (
	"context"
	"os"
	"os/exec"
	"testing"
)

func TestDetectDocumentTextRequiresTesseract(t *testing.T) {
	if _, err := exec.LookPath("tesseract"); err != nil {
		t.Skip("tesseract not installed")
	}
	ctx := context.Background()
	_, err := DetectDocumentText(ctx, []byte{}, ".png")
	if err == nil {
		t.Fatal("expected error for empty image")
	}
}

func TestDetectDocumentTextIntegration(t *testing.T) {
	if os.Getenv("TESSERACT_INTEGRATION") == "" {
		t.Skip("set TESSERACT_INTEGRATION=1 to run")
	}
	if _, err := exec.LookPath("tesseract"); err != nil {
		t.Skip("tesseract not installed")
	}
	// Minimal valid 1x1 PNG
	png := []byte{
		0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a,
		0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52,
		0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
		0x08, 0x06, 0x00, 0x00, 0x00, 0x1f, 0x15, 0xc4,
		0x89, 0x00, 0x00, 0x00, 0x0a, 0x49, 0x44, 0x41,
		0x54, 0x78, 0x9c, 0x63, 0x00, 0x01, 0x00, 0x00,
		0x05, 0x00, 0x01, 0x0d, 0x0a, 0x2d, 0xb4, 0x00,
		0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0xae,
		0x42, 0x60, 0x82,
	}
	ctx := context.Background()
	_, err := DetectDocumentText(ctx, png, ".png")
	if err != nil && err != ErrOCRNoText {
		t.Fatalf("unexpected: %v", err)
	}
}
